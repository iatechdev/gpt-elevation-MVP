export function landingFieldLabel(key: string, lang: 'es' | 'en'): string {
  if (!key.startsWith('landing.')) throw new Error(`Unknown landing field: ${key}`)
  return key.slice('landing.'.length).split('.').map(part => {
    if (/^\d+$/.test(part)) return part
    const faq = /^([qa])(\d+)$/.exec(part)
    if (faq) return `${faq[1] === 'q' ? (lang === 'es' ? 'Pregunta' : 'Question') : (lang === 'es' ? 'Respuesta' : 'Answer')} ${faq[2]}`
    const label = parts[part]
    if (!label) throw new Error(`Missing landing field label: ${part}`)
    return label[lang]
  }).join(' · ')
}
